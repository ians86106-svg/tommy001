# This program demonstrates basic list operations in Python.
students =["Alice", "Bill", "Charles", "Diana"]
print ("and the initial list of students is:", students)

# Add a new student to the list
students.append("Eve")
print ("After adding a new student, the list of students is:", students)

# Remove a student from the list
students.remove("Bill")
print ("After removing a student, the list of students is:", students)

# Sort the list of students
students.sort()
print ("After sorting the list of students is:", students)